/**
 * 버전 기록. 푸터의 버전 표기와 /changelog 페이지가 **이 목록 하나**를 본다.
 *
 * 올릴 때는 맨 앞에 한 줄 추가하면 끝이다 — APP_VERSION 이 목록의 첫 항목에서 나오므로
 * 푸터가 저절로 따라온다. 상수와 기록을 따로 두면 둘이 어긋나는데, 그 어긋남은 화면에
 * 잘 안 보인다(푸터는 1.0.2 인데 기록의 최신이 1.0.1 이어도 아무 데도 안 깨진다).
 *
 * **SemVer 로 올린다.** 어느 자리를 올릴지는 이렇게 가른다.
 *   Major  하위 호환이 깨질 때. 대대적인 변화. 이전 방식으로는 접속조차 안 될 때
 *   Minor  하위 호환을 지키면서 기능이 추가될 때. 기존 기능의 사용 방법이 바뀌었을 때
 *   Patch  버그 수정. 이용자가 알아차리지 못할 작은 변화. 내부 소스만 고쳤을 때
 *
 * README 머리의 표기는 여기 따라 자동으로 바뀌지 않는다. 주기적으로 한 번에 갱신한다.
 */
