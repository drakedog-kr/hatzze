import { C } from "../ui";

/**
 * 사자·팔자의 색 — **국내 관행을 따른다. 빨강이 사는 쪽, 파랑이 파는 쪽.**
 *
 * 처음엔 파랑(사자) + 회색(팔자)이었다. 우리 강조색이 파랑이라 자연스러웠지만, 한국
 * 독자에게는 오르면 빨강·내리면 파랑이 몸에 배어 있어 한 번씩 되짚어야 했다.
 *
 * ## 쓰는 자리
 *
 *   ✅ 달력 칸(CalendarHero)
 *   ✅ ETF 자금 유입(EtfCards 의 Flows) — 0 을 가운데 둔 양방향 막대
 *   ⏳ '평소와의 차이'(DailyCards 의 VsUsual) — 아직 파랑/회색
 *
 * 한 섹션씩 손보는 중이라 일부러 이렇게 두었다. **그 섹션에 손댈 때 이 파일을 보고
 * 같이 맞출 것** — 자리마다 색이 갈리면 페이지가 스스로 모순된다.
 *
 * ## 검증
 *
 * dataviz 검증기로 전 쌍을 쟀다 — 색약 ΔE 27.6(protan) / 정상 33.4 이고 명도·채도·
 * 배경대비까지 전부 PASS 다. 앞서 쓰던 회색 조합이 떨어뜨렸던 검사들이다.
 *
 *   node scripts/validate_palette.js "#d03a46,#3182f6" --mode light --pairs all
 *
 * ⚠️ 빨강은 브리핑의 **과열도 색(--c-hot)과 같은 값**이다. 충돌로 보일 수 있지만
 * 같은 문화적 매핑이다 — 많이 사면 뜨겁다. 새 빨강을 하나 더 만들면 사이트에 붉은색이
 * 둘이 되어 그게 더 나쁘다.
 *
 * ⚠️ 글자 강조(`Em`)는 그대로 파랑이다. 그건 '매도'가 아니라 '여길 봐라'라는 다른
 * 채널이라, 표시 색과 강조 색은 겹쳐도 된다.
 */
export const BUY = C.hot;
export const SELL = C.blue;

/**
 * ## ⚠️ 같은 빨강·파랑이라도 **면과 글자는 값이 다르다**
 *
 * 위 둘은 **면**(막대 · 달력 칸 · 범례 네모)에 쓰는 원색이다. 그대로 글자에 쓰면
 * 흰 카드 위 명암비가 파랑 **3.71** 로 떨어진다(4.5 미달). 저장소는 그래서 원색과
 * 별개로 '읽히는 값'을 따로 둔다 — `--c-hot-ink` · `--c-cold-ink` 다. 카더라와 MDD 가
 * 부호 있는 숫자에 이미 이 쌍을 쓴다.
 *
 *   흰 카드 위   BUY 4.80 / SELL 3.71   ·   BUY_INK 5.5 / SELL_INK 5.23
 */
export const BUY_INK = "var(--c-hot-ink)";
export const SELL_INK = "var(--c-cold-ink)";

/* `netTone(net)` 이 여기 있었다. 부르는 곳이 0 이다 — 달력이 `color-mix` 안에서
   `net >= 0 ? BUY : SELL` 을 직접 쓰면서 대체됐다(실수로 빠진 게 아니라 대체다). */

/**
 * 부호 있는 값의 **글자** 색 — 오르면 빨강, 내리면 파랑. 국내 관행이다.
 *
 * ⚠️ 이 페이지는 이걸 한참 안 지켰다. `+102%` 가 파랑, `+$1.18B` 가 검정이었다.
 * 파란 플러스는 한국 독자에게 손해로 읽힌다.
 *
 * ⛔ **'사는 양 88%' 같은 값에는 쓰지 말 것.** 저건 부호가 아니라 평소 대비 비율이라
 * 방향이 둘로 갈린다(덜 파는 것이 나쁜 일인가?). 그 자리 색은 잉크로 두고, 사자·팔자
 * 구분은 옆의 네모가 진다.
 */
export const signInk = (v: number) => (v >= 0 ? BUY_INK : SELL_INK);
