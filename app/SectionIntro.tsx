/**
 * 구간 머리 — **장 번호 + 큰 제목 한 줄.**
 *
 * 2026-09 토스 홈 리뉴얼의 어법을 빌렸다. 그 화면은 구간마다 큰 제목 하나로
 * 장을 가르고 그 아래에 카드가 온다. 여기서는 사이드바 안 본문이라 23px 로 줄였다.
 * 예전의 마이크로 캡스 배지(SectionCaps, "최근 뜨는 것 3")는 구간이 바뀐다는 신호가
 * 너무 작아서 스크롤하며 훑을 때 지나쳤다.
 *
 * ⭐ **번호(`n`)를 붙인다**(2026-09-05 확정). 후보 다섯을 나란히 세워 골랐다 —
 * 크기·여백만, 장 번호, 개수 칩, 강조 막대, 아이콘. 장 번호가 이긴 까닭은 이 화면들이
 * *목록*이 아니라 *읽는 순서가 있는 글*이기 때문이다. 번호는 "몇 장짜리 글의 어디쯤"을
 * 한 글자로 말해 준다("조건·행동을 구체적 숫자로", 토스 Marketing Writing).
 * 개수 칩은 아래 시트를 세면 알 수 있는 값이라 자리값이 낮았고, 막대와 아이콘은 장식이
 * 하나 더 느는 쪽이었다.
 *
 * ⚠️ 번호는 `aria-hidden` 이다. 눈으로 훑을 때의 길잡이일 뿐 제목의 이름이 아니라서,
 * 스크린 리더에는 "01 최근 뜨는 것" 이 아니라 "최근 뜨는 것" 으로 들려야 한다.
 *
 * ⚠️ **한 장뿐인 화면에는 번호를 주지 않는다**(거물 상세 `/insider/investor/[cik]`).
 * "01" 만 혼자 있으면 다음 장이 있다고 약속해 놓고 안 지키는 꼴이다. `n` 을 비우면 된다.
 *
 * h2 다. 시트 머리(SectionHead)는 이 아래라 level={3} 을 준다 — 한 층을 건너뛰면
 * 문서 개요가 깨진다(SectionHead 의 level 주석 참고).
 *
 * id 는 시장 브리핑의 딥링크(#market · #sentiment) 몫이다 — 그 화면의 옛 배지가 들고 있던 것.
 */
export function SectionIntro({
  n,
  title,
  sub,
  id,
}: {
  n?: number;
  title: string;
  sub?: string;
  id?: string;
}) {
  return (
    <div id={id} className="hz-tx-intro">
      <h2>
        {n != null && <i aria-hidden="true">{String(n).padStart(2, "0")}</i>}
        {title}
      </h2>
      {/* ⚠️ **부제는 기본이 아니다**(2026-09-05 지시로 전 화면에서 뺐다). 이 줄이 하는
          일은 이름 짓기가 아니라 **박자 만들기**이고, 아래 시트마다 제목과 부제가 이미
          있어서 여기에 한 줄을 더 얹으면 같은 말이 두 번 난다(Remove empty sentences).
          프롭은 남겨 둔다 — 시트가 스스로 설명하지 못하는 새 구간이 생기면 그때 쓴다. */}
      {sub && <p>{sub}</p>}
    </div>
  );
}
