from typing import NamedTuple


class Leg(NamedTuple):
    """한 방향(오른 날 또는 내린 날)의 성적."""

    n: int
    """그 방향 사건 수(5년)."""
    wins: int
    """국내 초과 개장 갭이 **미국과 같은 방향**이었던 횟수."""
    base: int
    """⭐ 같은 기간 아무 날이나 골랐을 때 그랬을 횟수. **wins 를 화면에 낼 때 항상 같이 낸다.**
    "173번 중 130번" 만 있으면 대단해 보이지만 옆에 "평소라면 92번" 이 있어야 읽힌다."""
    gap: float
    """그 사건들의 국내 **초과** 개장 갭 평균(%p). 쌍을 고르고 검증하는 데 쓴다."""
    open: float
    """⭐ 그 사건들의 국내 **날것** 개장 갭 평균(%). 화면에 내는 건 이 값이다 —
    "이런 날 흥구석유는 보통 +2.25% 열렸습니다" 가 사람이 읽는 문장이다."""
    kospi: float
    """같은 날들의 코스피 개장 갭 평균(%). 화면에는 안 낸다(잡음 수준이라 자리만 먹었다)."""
    intra: float
    """⭐⭐ 그 사건들의 **개장 뒤**(시가 → 종가) 평균(%).

    이 값이 0 언저리라는 게 이 화면의 성격을 정한다. 화면은 개장 / 개장 뒤 / 하루 전체
    셋을 나란히 내는데, **하루 전체는 저장하지 않고** (1+open)(1+intra)−1 로 낸다 —
    따로 담으면 셋이 안 맞는 날이 생긴다."""


class Pair(NamedTuple):
    ticker: str
    """미국 거래소 티커. `us_stocks.ticker` 와 같은 값."""
    stock: str
    """국내 종목명. KRX 정식 종목명(`stocks.name`)."""
    kind: str
    """관계 유형: supply · peer · cycle · license · channel · rival"""
    why: str
    """한 줄 근거. 화면에 그대로 쓸 수 있는 말로 적는다."""
    corr: float
    """미국 초과 등락 ↔ 다음 국내 초과 개장 갭의 상관(5년)."""
    up: Leg
    """미국이 평소의 1.0배 넘게 **오른** 날."""
    down: Leg
    """미국이 평소의 1.0배 넘게 **내린** 날."""


