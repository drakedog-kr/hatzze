# 이름 자체는 멀쩡한데 같은 문자열이 제품명·기술명으로도 쓰이는 자리다.
# 국내의 '동음이의'(결 ③)와 같은 부류라 이름을 죽이지 말고 **자리를 본다**.
# 값은 "이 패턴이 뒤에 붙으면 종목이 아니다".
#
# 실측 비중: RTX 173건 중 15건(8.7%)이 GPU 제품명 · ARM 160건 중 11건(6.9%)이 아키텍처.
NEGATIVE_CONTEXT: dict[str, str] = {
    "RTX": r"\s*\d{3,4}",                          # RTX 5090 = 엔비디아 GPU
    "ARM": r"\s*(?:아키텍처|기반|코어|칩|진영|계열)",   # ARM 기반 CPU
    "구글": r"\s*(?:트렌드|링|플레이|맵|드라이브|독스)",  # 구글 플레이스토어
}

# ── 한글 표기인데 다른 뜻으로 더 자주 쓰여 아예 뺀 것 ───────────────────────
#
# 여기 있는 이름은 사전에 **넣지 않는다**. 넣고 거르는 게 아니라 안 넣는다 —
# 경계 규칙으로는 못 가르고, 진짜 언급이 오탐보다 적어 넣을 값어치가 없다.
NAME_EXCLUDE: dict[str, str] = {
    "비자": "소비자·H-1B 비자. 실측 1,191건이 대부분 '소비자'였다",
    "블록": "블록체인·선체 블록·더 블록(매체). 표본 4건 중 3건 오탐",
    "이튼": "이튼 밴스(다른 회사)가 섞인다. 이턴(Eaton)으로만 받는다",
    "메이시스": "티커 M 이 일반 문자와 겹쳐 얻는 것보다 잃는 게 크다",
    "UPS": "무정전전원장치. 실측 114건 중 표본 2/3 이 전원장치였다",
}


def primary_names() -> dict[str, str]:
    """티커 → 화면에 쓸 대표 표기. 사전에 **먼저 나온** 표기를 고른다.

    별도 표시용 사전을 두지 않는다 — 179개를 두 벌로 관리하면 반드시 어긋난다.
    """
    out: dict[str, str] = {}
    for name, ticker in US_NAMES.items():
        out.setdefault(ticker, name)
    return out


def sanity_check() -> list[str]:
    """사전이 자기 규칙을 어기지 않았는지 본다. 스크립트가 시작할 때 부른다.

    손으로 잇는 목록이라 모순이 조용히 들어온다. 실제로 `ARM` 을 매칭 키로 쓰면서
    동시에 TICKER_NEVER_BARE 에 넣어 둔 적이 있다(뒤 문맥으로 가르기로 해서 뺐다).
    """
    problems = []
    for name in US_NAMES:
        if name in NAME_EXCLUDE:
            problems.append(f"{name}: 사전에 있으면서 NAME_EXCLUDE 에도 있다")
        if name in TICKER_NEVER_BARE:
            problems.append(f"{name}: 매칭 키인데 TICKER_NEVER_BARE 에 있다")
    for name in NEGATIVE_CONTEXT:
        if name not in US_NAMES:
            problems.append(f"{name}: NEGATIVE_CONTEXT 에만 있고 사전에 없다")
    return problems
