"""종목 이름 밑에 붙는 LLM 문장에서 매수·매도 표현·시세 낱말·언급 추이를 찾는다.

테마 요약(scripts/generate_theme_briefs.py)이 먼저 쓰던 그물을 종목 흐름 요약(국장·미장)도 같이 쓰도록
여기로 옮겼다. 흐름 요약은 글자 깨짐(common/text_check.problems)만 봤고, broadcast_content.BANNED_TERMS 는
채널 발송 글(safe_narrative)에서만 걸려 화면에는 그물 없이 나갔다.

2026-10-05 흐름 요약 27건(국장 15 · 미장 12) 실측:
  매수·매도·시세 4건 — "매수 의견이 제시되었습니다"(네패스) · "추천 종목으로 지목되며"(두산테스나) ·
                      "비중 확대 소식"(LG전자) · "저평가 구간이라는 분석"(삼성전자)
  언급 추이 7건     — "최근 3일 사이 관심이 급격히 줄어들었습니다"(심텍) 등. 그 사흘이 토·일·대체공휴일이라
                      전체 언급이 3,840 → 431 → 392 로 열 배 줄었다. 모든 종목이 같이 줄었는데 문장은
                      그 종목만 관심이 식은 것처럼 읽힌다.
"""
from __future__ import annotations

import re

from common.broadcast_content import banned_hits

# 이 화면에서만 더 막는 말. broadcast_content.BANNED_TERMS(매수 의견·매매 신호 …)는 발송 글의 그물이라
# 좁게 잡혀 있는데, 첫 실행(2026-09-19) 금융 요약이 "매수 기회를 제시하는 관점도 함께 나타났습니다"로
# 그 그물을 지났다. 채널이 한 말을 옮긴 전언이라도 공개 화면에서는 매수·매도 프레이밍이다.
EXTRA_BANNED = (
    "매수 기회", "매도 기회", "매수 타이밍", "매도 타이밍", "저가 매수", "추격 매수",
    "매수 관점", "매도 관점", "비중 확대", "비중 축소", "매수 전략", "매도 전략",
    # 붙여 쓴 꼴. 총평 셋째 대목 지시문(BRIEF_NEWS_COMMON)이 '비중확대'로 적는다.
    "비중확대", "비중축소", "매수의견", "매도의견",
    # 증권사 보고서의 추천 어휘. "SK텔레콤을 섹터 내 최우선 투자 대상으로 보는 의견"(2026-09-21 통신)처럼
    # 전언으로 옮겨도 화면에선 그 종목을 사라는 말이 된다.
    # 통신 요약을 세 번 다시 써도 "최우선 투자 대상" → "최우선 추천 종목" → "최우선주 · 투자 매력도"로 낱말만 바꿔
    # 되돌아왔다. 증권사 추천을 전언으로 옮기는 버릇이라, 낱말이 아니라 **뜻**을 막는다(프롬프트 규칙)하고
    # 그물도 그 뜻의 낱말 전부로 넓힌다.
    "최선호", "최우선", "투자 대상", "추천 종목", "추천주", "톱픽", "Top pick", "top pick",
    # 테마 상세 도는 얘기 첫 리허설(2026-10-05)에서 "태양광 업종 탑픽 선정" · "10월 종목 추천 대상"이 나왔다.
    "탑픽", "Top-Pick", "종목 추천", "추천 대상",
    "투자 매력", "매력도", "투자의견", "목표주가", "목표가",
)


# 시세를 말하는 낱말. 이 문장은 "무슨 얘기가 돌았나"만 맡고 등락은 화면의 다른 칸이 숫자로 적는다.
# 테마 요약 세 번째 실행(2026-09-19)에서 26건 중 3건이 "강세를 보였으며", "상승세 속에서"로 나왔다 — 채널이
# 그렇게 말한 것을 옮긴 것이지만, 우리 문장이 되면 시세 평가로 읽힌다. 다시 쓰게 하고, 끝내 못
# 고치면 저장은 한다(권유 표현과 달리 읽혀도 위험하지는 않다).
# 저평가·고평가는 증권사가 "싸다·비싸다"고 한 평가라 시세 낱말과 같은 자리다(2026-09-21 의료기기 까닭
# "저평가된 밸류에이션에 관한 보고서").
PRICE_WORDS = ("강세", "약세", "상승세", "하락세", "급등", "급락", "저평가", "고평가")


# 언급 추이. 흐름 요약 바로 곁에 일별 막대가 있어 추이는 그쪽이 보여 준다. 주말·휴장일엔 모든 종목이
# 함께 줄어(모듈 머리 실측) 문장으로 옮기면 그 종목 얘기처럼 읽힌다.
# 기간을 못박는 말은 예전 지시문("'최근 3일'처럼 범위를 못박으세요")이 추이 문장에 붙이게 한 것이라 함께 잡는다.
TREND_SPANS = ("최근 3일", "최근 사흘", "요 며칠", "지난 3일", "지난 사흘", "3일 사이", "사흘 사이", "며칠 사이")
# '언급이/관심이' 바로 뒤 두 어절 안에서 늘고 줆을 말하는 꼴. 주어를 언급·관심으로 좁힌다 —
# '화제'·'거론' 뒤에는 "거론된 데이터센터 투자 증가"처럼 내용 낱말이 온다.
TREND_RE = re.compile(r"(?:언급|관심)(?:이|은|도|량이|량은)?\s(?:\S+\s){0,2}?(?:줄|잦아|감소|급감|뜸해|식었|늘|증가|급증|높아|낮아)")


def trade_hits(text: str) -> list[str]:
    """매수·매도로 읽히는 말. 비어 있으면 통과."""
    return banned_hits(text) + [w for w in EXTRA_BANNED if w in text]


def has_trade_framing(text: str) -> bool:
    return bool(trade_hits(text))


def price_hits(text: str) -> list[str]:
    return [w for w in PRICE_WORDS if w in text]


def trend_hits(text: str) -> list[str]:
    return [w for w in TREND_SPANS if w in text] + [m.group(0) for m in TREND_RE.finditer(text)]


def drop_trade_sentences(text: str) -> str:
    """매수·매도 표현이 든 문장만 뺀다. 전부 걸리면 빈 문자열."""
    sents = re.split(r"(?<=다\.)\s+", text.strip())
    return " ".join(s for s in sents if s and not has_trade_framing(s))
