-- Hatzze — 마이그레이션 056: 국장 미리보기에 '몇 번 중 몇 번' 을 담는다
--
-- ## 왜 필요한가
--
-- 화면이 `gap`(초과 개장 갭의 평균 %p)만 보여 주고 있었는데, **내용을 아는 사람도 못
-- 읽었다**(2026-09-02). "+3.44%p" 는 '코스피 대비 초과 갭의 5년 평균' 이라는 통계학자의
-- 숫자라, 옆에 아무리 설명을 붙여도 한 번에 안 들어온다.
--
-- 사람이 한 번에 읽는 형태는 **횟수**다. "173번 중 130번 더 올랐습니다."
--
-- ⚠️ **`base` 를 함께 넣는 게 핵심이다.** "173번 중 130번" 만 있으면 대단해 보이지만,
--    옆에 "평소라면 92번" 이 있어야 그게 얼마짜리인지 읽힌다. 사전(us_kr_pairs.py)이
--    처음부터 못박아 둔 규칙이고, 그래서 두 컬럼을 **같이** 넣는다. 하나만 쓰지 말 것.
--
-- ## 값은 어디서 오나
--
-- `data-pipeline/config/us_kr_pairs.py` 의 `Pair.up` / `Pair.down` 이다. 파이프라인이
-- 그날 미국 종목의 **초과분 부호**를 보고 둘 중 맞는 쪽을 골라 넣는다(등락률 부호가
-- 아니다 — 시장이 3% 오른 날 1% 오른 종목은 사전 기준으로 '내린 날'이다).
--
-- 수치는 2026-09-02 에 최근 5년으로 **방향을 갈라** 다시 쟀다
-- (`data-pipeline/backtest/kr_preview_pairs.py`). 그전 값은 오른 날만, 그것도 1.5배
-- 문턱에서 잰 것이라 1.0배부터 카드로 내보내는 화면에는 붙일 수가 없었다.
--
-- Supabase SQL Editor에서 실행하세요.

alter table public.kr_preview_daily
  add column if not exists wins integer,
  add column if not exists base integer;

comment on column public.kr_preview_daily.wins is '⭐ 과거 그런 날(events 번) 가운데 국내 개장이 **미국과 같은 방향**이었던 횟수. 화면이 "173번 중 130번" 으로 읽는다';
comment on column public.kr_preview_daily.base is '⭐⭐ 같은 기간 아무 날이나 골랐을 때 그랬을 횟수. **wins 를 화면에 낼 때 항상 같이 낸다** — 옆에 이게 없으면 130번이 얼마짜리인지 못 읽는다';

-- ⚠️ 기존 줄에는 값이 없다(nullable). 파이프라인이 매 실행 그날 것을 통째로 갈아 끼우므로
--    다음 아침이면 다 찬다. 그동안 화면은 이 둘이 없으면 횟수 줄을 안 그린다.
