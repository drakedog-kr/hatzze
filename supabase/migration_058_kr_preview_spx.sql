-- Hatzze — 마이그레이션 058: 간밤 S&P500 등락을 함께 담는다
--
-- ## 왜 필요한가
--
-- 히어로 첫 칸이 "그날 어느 섹터가 움직였나" 를 목록으로 보이고 있었는데, 그건 이 화면이
-- 답해야 할 물음이 아니다. 사람이 개장 전에 궁금한 건 **"간밤 미국이 이랬는데 우리 장은
-- 어떻게 열리나"** 하나다.
--
-- 그 답을 낼 재료가 둘인데 하나가 표에 없었다.
--
--   · 구간별 코스피 성적 → `config/us_kr_pairs.py` 의 `KOSPI_AFTER` (5년 1,176일, 정적)
--   · **간밤 S&P500 등락** → 매일 달라지므로 여기 담는다
--
-- ## 이 표가 말하게 되는 것
--
-- 간밤 S&P 와 코스피 **개장 갭**의 상관은 0.547 인데 **장중**과는 0.018 이다.
-- 간밤 뉴스는 개장 순간에 다 반영되고 그 뒤로는 남는 게 없다 — S&P 가 1.5% 넘게 내린 날
-- 코스피는 개장 −1.17%, 종가까지 −1.21% 로 **하루 낙폭의 97%가 개장에서 났다.**
--
-- ⚠️ 값은 SPY(S&P500 ETF)의 등락률이다. 핀허브 무료가 지수(^GSPC)를 안 줘서 ETF 를 쓴다.
--    배당·괴리로 지수와 소수점이 조금 다르지만 이 용도로는 차이가 없다.
--
-- Supabase SQL Editor에서 실행하세요.

alter table public.kr_preview_daily
  add column if not exists spx_dp numeric;

comment on column public.kr_preview_daily.spx_dp is '⭐ 간밤 S&P500(SPY) 등락률(%). 화면이 이 값으로 KOSPI_AFTER 구간을 골라 "과거 이런 밤 뒤 코스피는 개장 −0.30%, 종가까지 −0.40%" 를 낸다';

-- ⚠️ 기존 줄에는 값이 없다(nullable). 파이프라인이 매 실행 그날 것을 통째로 갈아 끼운다.
