-- Hatzze — 마이그레이션 061: 쌍의 관계 **종류**를 함께 담는다
--
-- ## 왜 필요한가
--
-- 시트 머리의 부제가 고정 문구였다 — "미국 기업에 납품하거나 같은 업종이라…".
-- 그 문장은 그날 화면이 아니라 **사전 전체의 구성**을 말한 것이다(161쌍 중 같은 업종 84 ·
-- 납품 48 로 둘이 82%). 그래서 유가나 기술이전 쌍만 뜨는 날에는 화면에 없는 것을 가리킨다.
--
-- 그날 뜬 관계로 문장을 지으려면 줄마다 **종류**가 있어야 하는데, 지금 담는 `why` 는
-- "HBM TC본더"·"석유 유통" 같은 **개별 이름**이라 102가지다. 그걸 여섯 종류로 묶는 표를
-- 화면 쪽에 또 두면 파이썬 사전과 어긋나는 쌍둥이가 하나 더 생긴다.
--
-- ## 담기는 값
--
--   peer     같은 업종·동종      supply   납품·고객
--   cycle    같은 업황           license  기술이전
--   channel  유통 채널           rival    경쟁
--
-- `config/us_kr_pairs.py` 의 `Pair.kind` 를 그대로 넣는다. 사람이 읽을 말로 바꾸는 것은
-- 화면이 한다 — DB 에 한글을 넣으면 문구를 고칠 때마다 표를 다시 써야 한다.
--
-- ⚠️ 기존 줄에는 값이 없다(nullable). 화면은 종류가 하나도 없으면 예전 고정 문구로
--    물러선다 — 마이그레이션과 파이프라인 사이에 부제가 비는 일이 없게 한다.
--
-- Supabase SQL Editor에서 실행하세요.

alter table public.kr_preview_daily
  add column if not exists kind text;

comment on column public.kr_preview_daily.kind is '관계 종류(peer·supply·cycle·license·channel·rival). ⭐ 시트 부제가 그날 뜬 종류를 세어 "오늘은 같은 업종과 납품으로 엮인 곳입니다" 를 짓는다. 한글 표기는 화면이 정한다';
