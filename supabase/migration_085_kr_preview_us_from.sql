-- Hatzze — 마이그레이션 085: 국장 미리보기가 **연휴 동안 쌓인 미장 세션**을 알아보게 한다
--
-- ## 무엇을 고치나
--
-- 국장이 쉬는 동안 미장이 여러 번 열리면 연휴 뒤 첫 아침 카드는 그 세션들의 누적 등락이어야
-- 한다(백테스트가 그렇게 쟀다). 084 가 남기기 시작한 종가 기록(`quotes`)으로 수집기가 이제
-- 그 누적을 만든다. 이 칸은 **누적이 어느 세션부터인지**를 남겨 화면이 "연휴 동안" 으로 적게 한다.
--
-- ## 더하는 칸
--
--   us_from   누적이 시작된 미장 세션 날짜(미 동부). `us_session` 과 같으면 하루치(평소)이고,
--             앞이면 연휴 동안의 누적이다. 2026 추석 뒤 09-28(월)은 us_from 09-23 · us_session 09-25.
--
-- ⚠️ null 을 허용한다. 이 마이그레이션 전에 쓰인 줄은 비어 있고, 화면은 비어 있으면 예전처럼
--    "밤사이"/"금요일" 로 적는다.
-- ⚠️ **09-25(금) 06:30 실행 전에 실행하고 코드를 머지할 것.** 추석 중 누적이 처음 생기는 아침이
--    09-25 다(창 [09-23, 09-24]). 늦어도 09-28 06:30 전이면 연휴 뒤 첫 개장일은 맞는다.
-- ⚠️ 수집기는 이 칸이 없으면 이것만 빼고 다시 쓴다(종가 기록·휴장 칸은 지킨다).
--
-- Supabase SQL Editor에서 실행하세요.

alter table public.kr_preview_day add column if not exists us_from date;

comment on column public.kr_preview_day.us_from is '누적이 시작된 미장 세션(미 동부). us_session 과 같으면 하루치, 앞이면 연휴 동안의 누적이라 화면이 "연휴 동안" 으로 적는다';
