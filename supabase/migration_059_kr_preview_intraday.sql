-- Hatzze — 마이그레이션 059: 국내 종목의 '개장 뒤' 를 담는다
--
-- ## 왜 필요한가
--
-- 카드가 국내 종목마다 **개장 순간**만 보이고 있었다. 그런데 이 화면이 하려는 말은
-- "간밤 미국이 이랬으니 우리 장은 이렇게 열렸다" 로 끝나는 게 아니라,
-- **"그리고 그 뒤로는 별일 없었다"** 까지다.
--
-- 히어로는 이미 코스피로 그걸 보인다(개장 순간 / 개장 뒤 / 하루 전체). 종목 카드도 같은
-- 셋을 내야 앞뒤가 맞는다.
--
-- ## 왜 컬럼이 하나인가
--
-- **하루 전체는 담지 않는다.** (1+개장)(1+개장 뒤)−1 로 정확히 나오므로, 따로 담으면
-- 셋이 안 맞는 날이 생긴다. 화면에서 계산한다.
--
-- ## 이 값이 말하는 것
--
-- 깊은 쌍 62개 평균으로, 미국이 오른 날 국내 개장은 +0.95% 인데 개장 뒤는 +0.17% 다.
-- 내린 날은 개장 −0.57%, 개장 뒤 −0.30% 다. **개장에서 벌어진 것의 4분의 1 남짓만**
-- 장중에 더 간다.
--
-- ⚠️ 사전 주석에 "장중 기여 정확히 0" 이라고 적혀 있는데, 그건 적중률로 잰 값이다.
--    크기로 재면 작지만 0 은 아니다 — 화면 문구를 "거의 다 반영" 으로 적을 것.
--
-- Supabase SQL Editor에서 실행하세요.

alter table public.kr_preview_daily
  add column if not exists kr_intra numeric;

comment on column public.kr_preview_daily.kr_intra is '⭐ 과거 그런 날 이 국내 종목의 **개장 뒤**(시가 → 종가) 평균(%). 하루 전체는 담지 않는다 — (1+kr_open)(1+kr_intra)−1 로 화면이 낸다';
