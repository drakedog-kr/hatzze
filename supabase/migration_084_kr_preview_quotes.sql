-- Hatzze — 마이그레이션 084: 국장 미리보기가 매일 받은 **미장 종가를 전부** 남긴다
--
-- ## 무엇을 고치나
--
-- 국장이 쉬는 동안 미장이 여러 번 열리면(추석·설·징검다리 휴일) 연휴 뒤 첫 아침 카드는 그
-- 세션들의 **누적** 등락이어야 한다. 카드 수치를 낸 백테스트(data-pipeline/backtest/
-- kr_preview_pairs.py)가 그렇게 쟀다. 그런데 수집기가 받는 핀허브 quote 의 `dp` 는 마지막
-- 하루치뿐이라, 2026 추석 뒤 09-28(월) 카드에는 09-25(금) 하루만 담기고 09-23·24 세션이 빠진다.
--
-- 핀허브 무료는 과거 시세를 안 줘서 나중에 되받을 수 없다. 그래서 **받을 때 남긴다.** 수집기는
-- 이미 매일 아침(국장 휴일·주말 포함) 미국 80종목을 다 받는데, 지금은 문턱을 넘은 종목만 쓰고
-- 나머지를 버린다. 이 칸에 전부 남긴다. 연휴 뒤 누적은 "마지막 종가 ÷ 연휴 첫 세션의 전일 종가"
-- 로 이 기록에서 만든다(그 계산은 다음 작업이다).
--
-- ## 담기는 것
--
--   quotes   {"SPY": {"session": "2026-09-23", "c": 773.38, "pc": 773.5}, "NVDA": {...}, ...}
--            session  그 값이 속한 미장 세션 날짜(미 동부)
--            c        그 세션 종가
--            pc       전일 종가. ⭐ c / pc − 1 이 quote 의 dp 와 같다(2026-09-23 실측)
--            하루 5KB 남짓(81종목). 미장이 쉰 날은 부르지 않으므로 null 이다.
--
-- ⚠️ **09-24(목) 06:30 실행 전에 실행할 것.** 그 실행의 `pc` 가 09-22 종가이고, 추석 누적의
--    기준점이 바로 그 값이다. 놓치면 09-28 은 하루치로 간다.
-- ⚠️ 수집기는 이 칸이 없으면 이것만 빼고 다시 쓴다(휴장 표기 칸은 지킨다).
--
-- Supabase SQL Editor에서 실행하세요.

alter table public.kr_preview_day add column if not exists quotes jsonb;

comment on column public.kr_preview_day.quotes is '그 아침 받은 미장 종가 전부 {티커: {session, c, pc}}. 연휴 뒤 첫 아침의 누적 등락을 만드는 기록이다(핀허브 무료는 과거 시세를 안 준다)';
